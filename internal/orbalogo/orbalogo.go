// Package orbalogo carries the official Ordalie mark as pre-rendered art.
//
// Source of truth: https://ordalie.com/brand/ORDALIE_LOGO_ICONO_NOIR_FULL.svg,
// whose six contours resolve under an even-odd fill to the three nested rings
// of the mark. The rings' own bounding box (224x220 inside the padded 247x247
// viewBox) is what gets mapped, so the canvas carries the mark's proportions
// rather than the artboard's, rasterized offline onto one 24x11 monochrome
// Braille canvas per frame.
//
// The canvas is wider than it is tall in cells to cancel the cell aspect: a
// Braille cell is 2 dots wide and 4 dots tall, so 24x11 renders the 224x220
// mark at its true ratio when a terminal cell is about 1:2.14, which is where
// the common coding faces sit. Taller cells want a wider canvas and shorter
// cells a narrower one; only Width and the regeneration change.
//
// The mark is legible in the first frame and grows six percent while its dots
// arrive. Only finished frames ship; Orb does no image work at runtime.
